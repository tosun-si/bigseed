"""
A scenario pack: the unit generated by BigSeed and approved by a human, versioned in Git or in a versioned storage.

    pack.yaml                        the manifest: rules, data files, environments, sources
    bigtesty.yaml                    the datasets and tables, for BigTesty
    data/<dataset>/<table>.json      the generated rows: seeded into an environment AND loaded by the tests
    tests/**/*.bigtesty.yaml         the Given / When / Then scenarios, their given reading the data files

The same data files seed the environment (UAT...) and run the tests on ephemeral datasets: one source of truth.
"""

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Annotated, Any

import yaml
from pydantic import BaseModel, ConfigDict, Field, StringConstraints, ValidationError

from bigseed.errors import PackError

MANIFEST = "pack.yaml"
TableRef = Annotated[str, StringConstraints(pattern=r"^[A-Za-z0-9_]+\.[A-Za-z0-9_\-$]+$")]


class PackModel(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Source(PackModel):
    path: str = Field(description="Input the pack was generated from (SQL, Python, Java, Markdown spec...).")
    sha256: str = Field(description="Hash of the input at the generation: a changed input makes the pack stale.")


class Rule(PackModel):
    id: str = Field(description="Stable ID of the business rule, e.g. R1.")
    description: str = Field(description="The rule in business words: what the reviewer checks the scenarios against.")
    source: str = Field(description="Where the rule comes from, e.g. inputs/rules.md#L3-L5.")
    scenarios: list[str] = Field([], description="IDs of the BigTesty scenarios covering the rule (file::name).")


class Environment(PackModel):
    project: str
    datasets: dict[str, str] = Field(description="Configured dataset -> dataset of the environment.")
    seedable: bool = Field(True, description="false for an environment that must never be seeded (e.g. prod).")


class Manifest(PackModel):
    name: str
    version: int = Field(ge=1, description="Incremented at each approval: an environment is seeded from a version.")
    description: str | None = None
    sources: list[Source] = []
    rules: list[Rule] = Field(min_length=1)
    data: dict[TableRef, str] = Field(description="Table (dataset.table) -> its data file, relative to the pack.")
    environments: dict[str, Environment] = {}


@dataclass(frozen=True)
class Pack:
    root: Path
    manifest: Manifest

    @property
    def bigtesty_config(self) -> Path:
        return self.root / "bigtesty.yaml"

    def data_file(self, table: str) -> Path:
        return self.root / self.manifest.data[table]


def load_pack(root: Path) -> Pack:
    manifest_path = root / MANIFEST
    try:
        content = yaml.safe_load(manifest_path.read_text())
        return Pack(root.resolve(), Manifest.model_validate(content))
    except OSError as e:
        raise PackError(f"No pack in {root}: {e}") from e
    except (yaml.YAMLError, ValidationError) as e:
        raise PackError(f"Invalid {manifest_path}:\n{e}") from e


def load_rows(path: Path) -> list[dict[str, Any]]:
    try:
        rows = yaml.safe_load(path.read_text())  # JSON is YAML
    except (OSError, yaml.YAMLError) as e:
        raise PackError(f"Cannot read the data file {path}: {e}") from e
    if not isinstance(rows, list) or not all(isinstance(row, dict) for row in rows):
        raise PackError(f"The data file {path} must contain a list of rows")
    return rows


def sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()
